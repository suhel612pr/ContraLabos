const LangSwitcher = {
  current: (function(){
    try{ return localStorage.getItem("contralabos_lang") || "en"; }
    catch(e){ return "en"; }
  })(),

  apply(lang){
    this.current = lang;
    try{ localStorage.setItem("contralabos_lang", lang); }
    catch(e){ /* localStorage unavailable (e.g. private browsing) — continue in-memory */ }
    const dict = I18N[lang] || I18N.en;
    document.querySelectorAll("[data-i18n]").forEach(el => {
      const key = el.getAttribute("data-i18n");
      if(dict[key]) el.textContent = dict[key];
    });
    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
      const key = el.getAttribute("data-i18n-ph");
      if(dict[key]) el.setAttribute("placeholder", dict[key]);
    });
    document.querySelectorAll(".lang-select").forEach(sel => sel.value = lang);
    document.documentElement.setAttribute("lang", lang);
  },

  // Kept for backward compatibility — just resyncs current state.
  // Actual change-handling uses a single delegated listener below,
  // so it works regardless of when/where a .lang-select is added
  // to the page (static markup or injected later by shell.js).
  init(){
    this.apply(this.current);
  }
};

// Single delegated listener: catches change events from ANY .lang-select,
// present now or added to the DOM later. No per-element wiring needed,
// no risk of a select missing its listener due to render timing.
document.addEventListener("change", (e) => {
  if(e.target && e.target.matches && e.target.matches(".lang-select")){
    LangSwitcher.apply(e.target.value);
  }
});

document.addEventListener("DOMContentLoaded", () => LangSwitcher.apply(LangSwitcher.current));

// Global translation helper for JS-rendered content (stat cards, table rows,
// status badges, greetings) that doesn't exist in the HTML until a page's own
// script builds it at runtime — data-i18n attributes can't reach that content
// since it isn't in the DOM yet when apply() scans for [data-i18n] elements.
function t(key){
  const dict = I18N[LangSwitcher.current] || I18N.en;
  return dict[key] || I18N.en[key] || key;
}

// Translates lowercase enum/status values used in JS-rendered badges
// (e.g. "approved", "half-day", "payment") by mapping them to the same
// translations already written for their capitalized static-option form.
const ENUM_ALIAS = {
  "submitted":"ttl_Submitted","review":"ttl_Under Review","approved":"ttl_Approved",
  "rejected":"ttl_Rejected","completed":"ttl_Completed","active":"ttl_Active","inactive":"ttl_Inactive",
  "present":"ttl_Present","absent":"ttl_Absent","half-day":"ttl_Half-day","leave":"ttl_Leave",
  "paid":"ttl_Paid","unpaid":"ttl_Unpaid","payment":"ttl_Payment","material":"ttl_Material","expense":"ttl_Expense",
  "enabled":"ttl_Enabled","record only":"ttl_Record Only"
};
function tBadge(value){
  if(!value) return value;
  const key = ENUM_ALIAS[String(value).toLowerCase()];
  return key ? t(key) : value;
}

const ROLE_ALIAS = {
  "contractor":"ttl_Contractor / Owner","supervisor":"ttl_Site Supervisor",
  "worker":"ttl_Worker","accountant":"ttl_Accountant / Office Staff","admin":"ttl_Platform Administrator"
};
function tRole(value){
  if(!value) return value;
  const key = ROLE_ALIAS[String(value).toLowerCase()];
  return key ? t(key) : (value.charAt(0).toUpperCase()+value.slice(1));
}

// Fired every time the language changes, AFTER static content has been
// retranslated. Pages that render dynamic content (stat rows, table bodies)
// should listen for this and re-run their own render function so JS-built
// content updates too, not just static markup.
const _origApply = LangSwitcher.apply.bind(LangSwitcher);
LangSwitcher.apply = function(lang){
  _origApply(lang);
  document.dispatchEvent(new CustomEvent("languagechange:contralabos"));
};
